-- POSTMORTEM.RESULTS: base tables and the rule-id sequence.
-- DDL only. WARNING: CREATE OR REPLACE TABLE drops existing data.

create or replace sequence POSTMORTEM.RESULTS.LEARN_RULE_SEQ start with 1 increment by 1 noorder;
create or replace TABLE POSTMORTEM.RESULTS.BIAS_TAGS (
	POSTMORTEM_ID VARCHAR(16777216),
	DECISION_KEY VARCHAR(16777216),
	TAG VARCHAR(16777216),
	EVIDENCE VARCHAR(16777216),
	STRENGTH NUMBER(38,0),
	ABOUT VARCHAR(16777216)
);
create or replace TABLE POSTMORTEM.RESULTS.EVAL_HISTORY (
	CAPTURED_AT TIMESTAMP_LTZ(9),
	RUN_NAME VARCHAR(16777216),
	TARGET VARCHAR(16777216),
	METRIC_NAME VARCHAR(16777216),
	METRIC_TYPE VARCHAR(16777216),
	AVG_SCORE FLOAT,
	N NUMBER(38,0),
	REF_BUILT_AT TIMESTAMP_LTZ(9)
);
create or replace TABLE POSTMORTEM.RESULTS.EVAL_PIPELINE (
	CHECKED_AT TIMESTAMP_LTZ(9),
	CHECK_ID VARCHAR(16777216),
	KIND VARCHAR(16777216),
	CHECK_NAME VARCHAR(16777216),
	RESULT VARCHAR(16777216),
	DETAIL VARCHAR(16777216)
);
create or replace TABLE POSTMORTEM.RESULTS.EVAL_POSTMORTEM_ANALYST (
	INPUT_QUERY VARCHAR(16777216),
	GROUND_TRUTH VARIANT
);
create or replace TABLE POSTMORTEM.RESULTS.EVAL_REF (
	BUILT_AT TIMESTAMP_LTZ(9),
	BEST_SOURCE VARCHAR(16777216),
	BEST_ABS FLOAT,
	BEST_N NUMBER(18,0),
	FIRM_X_MEAN FLOAT,
	FIRM_X_N NUMBER(18,0),
	GUIDE_MEAN FLOAT,
	GUIDE_ABS FLOAT,
	GUIDE_N NUMBER(18,0),
	CLAUDE_48_MEAN FLOAT,
	CLAUDE_48_N NUMBER(18,0),
	CLONE_VS_INDEP VARCHAR(16777216),
	BIG_MISS_DK VARCHAR(16777216),
	BIG_MISS_ERR FLOAT,
	TOP_TAG VARCHAR(16777216),
	TOP_FIRM_X_TAG VARCHAR(16777216)
);
create or replace TABLE POSTMORTEM.RESULTS.LEARN_PLAYBOOKS (
	PLAYBOOK_ID VARCHAR(16777216),
	PURPOSE VARCHAR(16777216),
	TARGET_KEY VARCHAR(16777216),
	HOLDOUT_KEY VARCHAR(16777216),
	CREATED_AT TIMESTAMP_LTZ(9),
	RULE_IDS ARRAY,
	TEXT VARCHAR(16777216)
);
create or replace TABLE POSTMORTEM.RESULTS.LEARN_RULES (
	RULE_ID VARCHAR(16777216),
	SOURCE_KEY VARCHAR(16777216),
	POSTMORTEM_ID VARCHAR(16777216),
	CREATED_AT TIMESTAMP_LTZ(9),
	RULE VARCHAR(16777216),
	SIGNAL VARCHAR(16777216),
	DIRECTION VARCHAR(16777216),
	APPLIES_TO VARCHAR(16777216),
	GATE_OK BOOLEAN,
	GATE_HIT VARCHAR(16777216)
);
create or replace TABLE POSTMORTEM.RESULTS.PM_REPORT_CHUNKS (
	CHUNK_ID VARCHAR(16777216),
	DECISION_KEY VARCHAR(16777216),
	SECTION VARCHAR(50),
	CHUNK VARCHAR(16777216)
);
create or replace TABLE POSTMORTEM.RESULTS.POSTMORTEMS (
	POSTMORTEM_ID VARCHAR(16777216),
	DECISION_KEY VARCHAR(16777216),
	MODEL VARCHAR(16777216),
	CREATED_AT TIMESTAMP_LTZ(9),
	PARSED VARIANT,
	RAW_RESPONSE VARCHAR(16777216),
	MODE VARCHAR(16777216)
);
create or replace TABLE POSTMORTEM.RESULTS.REPLAY_IMPORTS (
	RUN_ID VARCHAR(16777216),
	SOURCE_ACCOUNT VARCHAR(16777216),
	DOCS_CHECKSUM NUMBER(38,0),
	EXPORTED_AT TIMESTAMP_LTZ(9),
	IMPORTED_AT TIMESTAMP_LTZ(9)
);
create or replace TABLE POSTMORTEM.RESULTS.REPLAY_RUNS (
	RUN_ID VARCHAR(16777216),
	DECISION_KEY VARCHAR(16777216),
	MODE VARCHAR(16777216),
	MODEL VARCHAR(16777216),
	RUN_AT TIMESTAMP_LTZ(9),
	FY1_GROWTH_PCT FLOAT,
	FY2_GROWTH_PCT FLOAT,
	FY3_GROWTH_PCT FLOAT,
	CONFIDENCE NUMBER(38,0),
	PARSED VARIANT,
	RAW_RESPONSE VARCHAR(16777216),
	PROMPT_CHARS NUMBER(38,0),
	PLAYBOOK_ID VARCHAR(16777216)
);
